#!/usr/bin/env node
/*
 * build-configurator-comps.cjs — 레포 컴포넌트 토큰 → 컨피규레이터 주입 블록 (공식 빌드)
 *
 * 왜: 컨피규레이터의 컴포넌트 토큰 표(CGEO·CCOL)가 **손으로 유지되는 사본**이었다.
 *     그래서 레포가 8종 → 29종으로 늘어도 화면은 8종에 머물렀다(진아 지적 2026-08-06:
 *     "업데이트된 내용이 컨피규레이터에도 당연히 업데이트되어야 한다").
 *     결정 #29 "복사가 아니라 생성" 을 컴포넌트 층에도 적용한다 — 표는 이제 생성물이다.
 *
 * 무엇: tokens/component/*.json 을 읽어 { 컴포넌트, 토큰경로, 시맨틱 참조 } 목록을 만들고,
 *     public/index.html 의 생성 구역(마커 사이)에 JS 리터럴로 주입한다.
 *     **값을 굽지 않는다** — 참조만 넣고, 실제 색·치수는 컨피규레이터가 지금 파라미터로
 *     살아 있는 roles() 에서 해석한다. 값을 구우면 슬라이더를 움직여도 표가 안 따라온다.
 *
 * 하드 게이트: 모든 참조가 SEM_MAP(컨피규레이터 쪽 해석 표)에 있어야 한다.
 *     새 컴포넌트가 매핑 없는 역할을 쓰면 조용히 빈칸이 되는 대신 여기서 빌드가 실패한다.
 *
 * 사용: node scripts/build-configurator-comps.cjs          # 주입
 *       node scripts/build-configurator-comps.cjs --check  # 드리프트 검사(CI)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const CDIR = path.join(ROOT, 'tokens', 'component');
const TARGET = path.join(ROOT, 'public', 'index.html');
const BEGIN = '/* ▼▼ AUTO-GENERATED by scripts/build-configurator-comps.cjs — 직접 수정 금지 ▼▼ */';
const END   = '/* ▲▲ AUTO-GENERATED END ▲▲ */';

/** 파일명 → 컨피규레이터가 쓸 컴포넌트 키(= 토큰 루트 키) */
function collect() {
  const out = [];
  const files = fs.readdirSync(CDIR).filter(f => f.endsWith('.json')).sort();
  for (const f of files) {
    const j = JSON.parse(fs.readFileSync(path.join(CDIR, f), 'utf8'));
    const name = Object.keys(j.component)[0];
    const rows = [];
    const walk = (node, trail) => {
      for (const [k, v] of Object.entries(node)) {
        if (k.startsWith('$')) continue;
        if (!v || typeof v !== 'object') continue;
        const p = trail.concat(k);
        if (typeof v.$value === 'string' && v.$value.startsWith('{semantic.')) {
          rows.push({ t: p.join('.'), ref: v.$value.slice(10, -1) });
        } else if (v.$extensions && v.$extensions.rule && v.$value) {
          // 규칙 실체화(computed) — 참조가 아니라 계산된 값. px 를 그대로 싣고 근거를 남긴다.
          rows.push({ t: p.join('.'), px: v.$extensions.px, rule: (v.$extensions.rule.formula || v.$extensions.rule.type) });
        } else walk(v, p);
      }
    };
    walk(j.component[name], []);
    out.push({ c: name, file: f.replace(/\.json$/, ''), rows });
  }
  return out;
}

const comps = collect();
const refs = new Set();
comps.forEach(c => c.rows.forEach(r => r.ref && refs.add(r.ref)));

/* 하드 게이트 — 모든 참조가 컨피규레이터의 SEM_MAP 에 있어야 한다.
 * 없으면 화면에 조용한 빈칸이 생긴다. 새 컴포넌트가 매핑 없는 역할을 쓰는 순간 여기서 멈춘다. */
{
  const src = fs.readFileSync(TARGET, 'utf8');
  const m = src.match(/function SEM_MAP\(R\)\{[\s\S]*?\n\}/);
  if (!m) { console.error('build-configurator-comps: public/index.html 에 SEM_MAP() 이 없습니다.'); process.exit(1); }
  const missing = [...refs].filter(r => !m[0].includes('"' + r + '"'));
  if (missing.length) {
    console.error('build-configurator-comps: SEM_MAP 에 없는 시맨틱 참조 ' + missing.length + '건 —');
    missing.forEach(r => console.error('  ✗ ' + r));
    console.error('\npublic/index.html 의 SEM_MAP() 에 이 역할들을 추가하세요. 빠지면 화면에 빈칸이 생깁니다.');
    process.exit(1);
  }
}

const block =
  BEGIN + '\n' +
  '/* 레포 tokens/component/*.json 에서 생성. 값이 아니라 **참조**만 담는다 —\n' +
  '   실제 색·치수는 화면의 roles() 가 지금 파라미터로 해석한다. */\n' +
  'const COMP_SPEC = ' + JSON.stringify(comps) + ';\n' +
  'const COMP_REFS = ' + JSON.stringify([...refs].sort()) + ';\n' +
  END;

function inject() {
  let s = fs.readFileSync(TARGET, 'utf8');
  const i = s.indexOf(BEGIN), j = s.indexOf(END);
  if (i < 0 || j < 0) {
    console.error('build-configurator-comps: public/index.html 에 생성 구역 마커가 없습니다.');
    console.error('  다음 두 줄을 <script> 안에 넣어 두세요:\n  ' + BEGIN + '\n  ' + END);
    process.exit(1);
  }
  return s.slice(0, i) + block + s.slice(j + END.length);
}

const next = inject();
const total = comps.reduce((n, c) => n + c.rows.length, 0);

if (process.argv.includes('--check')) {
  const cur = fs.readFileSync(TARGET, 'utf8');
  if (cur !== next) { console.error('configurator-comps DRIFT — 레포 컴포넌트 토큰이 바뀌었는데 컨피규레이터에 반영되지 않았습니다.\n  고치려면: node scripts/build-configurator-comps.cjs'); process.exit(1); }
  console.log(`configurator-comps --check OK · ${comps.length}종 · 토큰 ${total}행 · 참조 ${refs.size}종`);
} else {
  fs.writeFileSync(TARGET, next);
  console.log(`build-configurator-comps: ${comps.length}종 · 토큰 ${total}행 · 참조 ${refs.size}종 → public/index.html`);
}
